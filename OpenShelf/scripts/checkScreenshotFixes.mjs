import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const get = (path) => readFileSync(resolve(root, path),'utf8');
const palette = get('client/src/styles/apple-homeview-colors.css');
assert.match(palette,/--openshelf-primary:\s*#0769D7/i);
assert.match(palette,/--openshelf-secondary:\s*#FFF9E6/i);
assert.match(palette,/\.home-gradient,\.gradient-text,\.books-hero h1 span,\.student-hero h1 span,\.peer-hero em\s*\{[\s\S]*?background-clip:\s*text;/);
assert.match(palette,/\.student-info\s*\{\s*background:#EFF7FF/);
const library=get('client/src/pages/StudentLibrary.jsx');
assert.match(library,/student-info'\} role="status"/);
assert.match(library,/₹10 Razorpay test purchase/);
const panel=get('client/src/components/dashboard/StudentPhysicalBorrowPanel.jsx');
assert.doesNotMatch(panel,/Free PDF reading|read PDFs for free/);
assert.match(panel,/₹10 Razorpay test purchase/);
const admin=get('client/src/pages/AdminDashboard.jsx');
assert.doesNotMatch(admin,/FREE PDF ·/);
const borrow=get('client/src/components/admin/AdminBorrowingDesk.jsx');
assert.doesNotMatch(borrow,/₹10 per overdue day/);
assert.match(borrow,/flat ₹10 per late return/);
const general=get('client/src/pages/GeneralBooks.jsx');
assert.match(general,/book\.coverUrl \|\| GENERAL_BOOK_COVER/);
console.log('Screenshot regressions: palette, heading clip, PDF wording, status colors and metadata checks passed.');
